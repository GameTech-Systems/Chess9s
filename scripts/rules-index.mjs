// Write packages/online/src/rules-index.ts: a static index of every JSON file in rules/, keyed by
// its path under rules/, for code that has no file system and no Vite (the online server, S51).
// A test fails when the index and the folder differ. Usage: pnpm rules:index
import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const root = new URL('../', import.meta.url).pathname;
const rulesDir = join(root, 'rules');
const out = join(root, 'packages/online/src/rules-index.ts');

const walk = (dir) =>
  readdirSync(dir).flatMap((f) => {
    const path = join(dir, f);
    return statSync(path).isDirectory() ? walk(path) : [path];
  });

const paths = walk(rulesDir)
  .filter((f) => f.endsWith('.json'))
  .map((f) => relative(rulesDir, f).split('\\').join('/'))
  .sort();

const lines = [
  '// Generated by `pnpm rules:index` (scripts/rules-index.mjs) from rules/. Do not edit by hand.',
  "import type { RulesFiles } from '@chess9s/engine';",
  ...paths.map((p, i) => `import f${i} from '../../../rules/${p}';`),
  '',
  '/** Every JSON file in rules/, keyed by its path under rules/. */',
  'export const rulesFiles: RulesFiles = {',
  ...paths.map((p, i) => `  '${p}': f${i},`),
  '};',
  '',
];
writeFileSync(out, lines.join('\n'));
console.log(`Wrote ${relative(root, out)} (${paths.length} files)`);
